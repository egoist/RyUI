//go:build ignore

// gen_symbols writes the web host's symbols (platform/web/src/symbols.js):
// the SF Symbol names ui.Symbol and ui.Icon take, as the Android host's
// Material Symbols (Apache 2.0) draw them, read from its vector drawables
// and its table (Symbols.kt), which platform/android/gen_symbols.go
// writes. Run it after that one:
//
//	go run platform/web/gen_symbols.go
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

var (
	entryRe = regexp.MustCompile(`"([^"]+)" to R\.drawable\.(asuka_sym_[a-z0-9_]+)`)
	labelRe = regexp.MustCompile(`"([^"]+)" to "([^"]*)"`)
	pathRe  = regexp.MustCompile(`android:pathData="([^"]+)"`)
)

func main() {
	android := filepath.Join("platform", "android", "asuka", "src", "main")
	kt, err := os.ReadFile(filepath.Join(android, "java", "dev", "asuka", "Symbols.kt"))
	if err != nil {
		panic(err)
	}
	src := string(kt)
	table, labelsPart, _ := strings.Cut(src, "symbolLabels")
	paths := map[string]string{} // drawable -> path data
	names := map[string]string{} // SF name -> drawable
	for _, m := range entryRe.FindAllStringSubmatch(table, -1) {
		names[m[1]] = m[2]
		if _, ok := paths[m[2]]; ok {
			continue
		}
		x, err := os.ReadFile(filepath.Join(android, "res", "drawable", m[2]+".xml"))
		if err != nil {
			panic(err)
		}
		var ds []string
		for _, p := range pathRe.FindAllStringSubmatch(string(x), -1) {
			ds = append(ds, p[1])
		}
		paths[m[2]] = strings.Join(ds, " ")
	}
	labels := map[string]string{}
	for _, m := range labelRe.FindAllStringSubmatch(labelsPart, -1) {
		labels[m[1]] = m[2]
	}
	var drawables []string
	for d := range paths {
		drawables = append(drawables, d)
	}
	sort.Strings(drawables)
	var sf []string
	for n := range names {
		sf = append(sf, n)
	}
	sort.Strings(sf)

	var b strings.Builder
	b.WriteString("// Code generated by platform/web/gen_symbols.go; DO NOT EDIT.\n\n")
	b.WriteString("// The symbols the web host draws, by SF Symbol name: Material Symbols\n// (Apache 2.0), as the Android host draws them. Paths are in Material's\n// 960-unit box, whose y runs from -960 to 0.\n\n")
	b.WriteString("const p = [\n")
	index := map[string]int{}
	for i, d := range drawables {
		index[d] = i
		fmt.Fprintf(&b, "  %q,\n", paths[d])
	}
	b.WriteString("];\n\n/** paths: SF Symbol name -> SVG path data. */\nexport const paths = {\n")
	for _, n := range sf {
		fmt.Fprintf(&b, "  %q: p[%d],\n", n, index[names[n]])
	}
	b.WriteString("};\n\n/** labels: what a screen reader says for a symbol shown alone (English). */\nexport const labels = {\n")
	for _, n := range sf {
		if l := labels[n]; l != "" {
			fmt.Fprintf(&b, "  %q: %q,\n", n, l)
		}
	}
	b.WriteString("};\n")
	out := filepath.Join("platform", "web", "src", "symbols.js")
	if err := os.WriteFile(out, []byte(b.String()), 0o644); err != nil {
		panic(err)
	}
	fmt.Printf("%d symbols, %d paths\n", len(sf), len(drawables))
}
