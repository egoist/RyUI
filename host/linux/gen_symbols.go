//go:build ignore

// gen_symbols writes the Linux host's fallback symbols (symbols_gen.go):
// the SF Symbol names ui.Symbol and ui.Icon take that the icon theme has
// no icon for are drawn as Material Symbols (Apache 2.0), as the Android
// and web hosts draw them, read from the web host's table, which
// platform/web/gen_symbols.go writes. Run it after that one:
//
//	go run host/linux/gen_symbols.go
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"strings"
)

var (
	pathRe  = regexp.MustCompile(`(?m)^  "([^"]*)",$`)
	entryRe = regexp.MustCompile(`(?m)^  "([^"]+)": p\[(\d+)\],$`)
	labelRe = regexp.MustCompile(`(?m)^  "([^"]+)": "([^"]*)",$`)
)

func main() {
	js, err := os.ReadFile("platform/web/src/symbols.js")
	if err != nil {
		panic(err)
	}
	src := string(js)
	pathsPart, rest, _ := strings.Cut(src, "export const paths")
	entriesPart, labelsPart, _ := strings.Cut(rest, "export const labels")
	var b bytes.Buffer
	b.WriteString("// Code generated by host/linux/gen_symbols.go; DO NOT EDIT.\n\n//go:build linux && !android\n\npackage linux\n\n")
	b.WriteString("// materialPaths are Material Symbols (Apache 2.0) as SVG path data, in\n// Material's 960-unit box, whose y runs from -960 to 0.\nvar materialPaths = [...]string{\n")
	for _, m := range pathRe.FindAllStringSubmatch(pathsPart, -1) {
		fmt.Fprintf(&b, "\t%q,\n", m[1])
	}
	b.WriteString("}\n\n// materialSymbols are the SF Symbol names drawn with materialPaths.\nvar materialSymbols = map[string]uint16{\n")
	for _, m := range entryRe.FindAllStringSubmatch(entriesPart, -1) {
		fmt.Fprintf(&b, "\t%q: %s,\n", m[1], m[2])
	}
	b.WriteString("}\n\n// symbolLabels are what screen readers say for a symbol.\nvar symbolLabels = map[string]string{\n")
	for _, m := range labelRe.FindAllStringSubmatch(labelsPart, -1) {
		fmt.Fprintf(&b, "\t%q: %q,\n", m[1], m[2])
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("host/linux/symbols_gen.go", out, 0o644); err != nil {
		panic(err)
	}
}
